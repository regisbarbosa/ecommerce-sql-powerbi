DECLARE @i INT = 0;

WHILE @i < 5000
BEGIN
    INSERT INTO vendas (id_cliente, id_produto, quantidade, data_venda, forma_pagamento)
    VALUES (
        ABS(CHECKSUM(NEWID()) % 100) + 1,                        -- id_cliente entre 1 e 100
        ABS(CHECKSUM(NEWID()) % 25) + 1,                         -- id_produto entre 1 e 25
        ABS(CHECKSUM(NEWID()) % 5) + 1,                          -- quantidade entre 1 e 5
        DATEADD(DAY, ABS(CHECKSUM(NEWID()) % 1095), '2022-01-01'), -- data aleatória entre 2022 e 2024
        CHOOSE(ABS(CHECKSUM(NEWID()) % 3) + 1, 'Crédito', 'Débito', 'Pix') -- forma_pagamento
    );

    SET @i += 1;
END;

-- Corrigir vendas com forma_pagamento IS NULL
UPDATE vendas
SET forma_pagamento = 
    CASE (ABS(CHECKSUM(NEWID()) % 3))
        WHEN 0 THEN 'Crédito'
        WHEN 1 THEN 'Débito'
        WHEN 2 THEN 'Pix'
    END
WHERE forma_pagamento IS NULL;

----- Verificar quantas vendas ainda estão com forma_pagamento IS NULL
SELECT COUNT(*) AS vendas_nulas
FROM vendas
WHERE forma_pagamento IS NULL;

